/**
 * 代理密码的「脱敏占位符」规则。
 *
 * ── 为什么单独抽一个文件 ──
 * 这条规则横跨两侧：
 * - **写回**（主进程）：界面拿到的密码永远是占位符，用户改了主机或端口
 *   顺手一保存，占位符就回来了 —— 直接写盘的话**真密码被占位符覆盖**。
 *   症状极难查：代理还在、主机端口都对，只是"突然不认密码了"，
 *   而真因是用户刚才点了一下保存（改的其实是屏幕分辨率）。
 * - **显示**（渲染层）：占位符不能显示成一串圆点 ——
 *   那看起来就像"这是你设的密码"。
 *
 * 放在 shared 是因为两侧必须用**同一份**判定；
 * 放在这里（而不是塞进 store 或组件）是因为它必须是**纯函数**才能被单测钉住 ——
 * 这条规则被破坏过一次，症状又是最难查的那种，不能只靠代码评审。
 *
 * 归属：profiles-agent
 */

/**
 * 代理密码的脱敏占位符。
 *
 * 代理密码是明文进主进程、密文落盘的敏感值，对外（渲染层）一律换成这个占位符。
 *
 * 为什么写回时也必须认得它：界面拿到的密码永远是占位符，
 * 如果用户改了别的字段就保存，占位符会被原样写回盘上 —— 真密码就此消失
 * （症状是"代理突然不认密码了"，没人会想到是自己刚才点了一下保存）。
 *
 * 所以写路径必须有一条明确规则：**占位符 = "不改这个字段"**。
 */
export const MASKED_SECRET = '••••••'

/** 这个值是不是脱敏占位符 */
export function isMaskedSecret(value: string | undefined | null): boolean {
  return value === MASKED_SECRET
}

/**
 * 写回时的密码合并规则。
 *
 * - 传入的是占位符 → 保留盘上那份（**不改**这个字段）；
 * - 传入空串 → 明确清空密码（用户主动清空的意图必须被尊重）；
 * - 其他 → 当成新密码。
 *
 * `existing` 为 undefined 表示盘上本来就没有密码，
 * 这时占位符应当落成空串 —— 不能凭空造出一个密码。
 */
export function mergeProxyPassword(
  incoming: string | undefined,
  existing: string | undefined
): string | undefined {
  if (incoming !== MASKED_SECRET) return incoming
  return existing ?? ''
}
